from discord import (
	Cog, Bot, ApplicationContext, Message, Member
)
from discord import option
from discord.ext.commands import slash_command as command
from datetime import datetime as dt, timezone as tz, timedelta as td
from math import floor
from json import load, dump

from os import getcwd
import sys

sys.path.append(getcwd()+'/../')

from utils.functions import log
from utils.autocomplete import AutoComplete

class Trolls(Cog):
	def __init__(self, bot: Bot) -> None:
		log('[Trolls] Loading extension \'Trolls\'...')
		super().__init__()
		self.bot: Bot = bot
		self.cpReceiveMode: bool = False
		self.cpName: str|None = None
		self.cpReceiveTarget: Member|None = None
		log('[Trolls] Extension \'Trolls\' loaded.')
		return
	
	@command(
		name = 'cp',
		description = 'コピペを貼ります [Extension: Trolls]'
	)
	@option(
		name = 'name',
		type = str,
		description = '登録してあるコピペ名',
		autocomplete = AutoComplete.getCPNameListAsync,
		required = True
	)
	async def __cp(self, ctx: ApplicationContext, name: str) -> None:
		cplist = AutoComplete.getCPNameList()
		if name not in cplist:
			await ctx.respond('Error: コピペ名 `%s` は存在しません！' % name)
			return
		with open('./cp-list.json', 'r') as fp:
			json: list[dict[str, str|int]] = load(fp)
		for row in json:
			if row['name'] == name:
				await ctx.respond(row['content'])
				return

	@command(
		name = 'cp-manage',
		description = 'コピペを管理します [Extension: Trolls]'
	)
	@option(
		name = 'mode',
		type = str,
		description = 'モードを指定します',
		choices = [
			'add',
			'remove'
		],
		required = True
	)
	@option(
		name = 'name',
		type = str,
		description = 'コピペの名前を指定します',
		autocomplete = AutoComplete.getCPNameListAsync,
		required = False
	)
	async def __cp_manage(self, ctx: ApplicationContext, mode: str, name: str|None = None) -> None:
		match mode:
			case 'add':
				if not name:
					await ctx.respond('Error: コピペ名を指定してください！')
					return
				cpNameList = AutoComplete.getCPNameList()
				if name in cpNameList:
					await ctx.respond('Error: コピペ名 `%s` は既に登録されています！' % name)
					return
				self.cpReceiveMode = True
				self.cpName = name
				self.cpReceiveTarget = ctx.author
				await ctx.respond('登録するコピペを張り付けて送信してください:\n\nコピペ名: `%s`' % name)
				return
			case 'remove':
				if not name:
					await ctx.respond('Error: コピペ名を指定してください！')
					return
				cpNameList = AutoComplete.getCPNameList()
				if name not in cpNameList:
					await ctx.respond('Error: コピペ名 `%s` は存在しません！' % name)
					return
				json2: list[dict[str, str|int]] = []
				with open('./cp-list.json', 'r') as fp:
					json: list[dict[str, str|int]] = load(fp)
				for row in json:
					if not row['name'] == name:
						json2.append(row)
					else:
						if not row['author'] == ctx.author.id:
							await ctx.respond('Error: 自分で登録したコピペ以外は削除できません！')
							return
				with open('./cp-list.json', 'w') as fp:
					dump(json2, fp)
				await ctx.respond('コピペ `%s` を削除しました！' % name)
				return
	
	@Cog.listener()
	async def on_message(self, message: Message) -> None:
		if not self.cpReceiveMode:
			return
		if not message.author == self.cpReceiveTarget:
			return
		
		cpData = {
			'name': self.cpName,
			'author': self.cpReceiveTarget.id,
			'createdAt': floor(dt.now().astimezone(tz(td(hours=9))).timestamp()),
			'content': message.content
		}
		with open('./cp-list.json', 'r') as fp:
			json: list[dict[str, str|int]] = load(fp)
		json.append(cpData)
		with open('./cp-list.json', 'w') as fp:
			dump(json, fp)
		self.cpReceiveMode = False
		self.cpReceiveTarget = self.cpName = None
		await message.reply('コピペ `%s` を登録しました！' % cpData['name'])
		return

def setup(bot: Bot):
	bot.add_cog(Trolls(bot=bot))